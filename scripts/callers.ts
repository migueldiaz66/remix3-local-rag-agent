// callers.ts: writes docs/callers.md, the index of every export and where it is used.
//
// Objective
//   Give the "Called by" lines of the function headers an exact source. The script lists each
//   export of each TypeScript file under app/, scripts/ and the root, and every other file that
//   mentions that name, with the line numbers.
//
// Dependencies
//   node:fs: readdirSync and statSync to walk the roots, readFileSync to read each file once,
//   mkdirSync and writeFileSync to create docs/ and write the index. node:path: join to build
//   paths, relative and sep to print them with forward slashes. No package.
//
// Consumers
//   `npm run callers` (package.json). People and agents read docs/callers.md; nothing imports
//   this file.
//
// How it relates to them
//   The index is a text search by word, not a type-aware analysis: a name used in a comment or a
//   string counts as a use. That is accepted: it errs on the side of listing a caller.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

/**
 * The folders and files scanned, relative to the working directory (the repository root): the
 * app, the scripts and the two entry points at the root.
 */
const ROOTS = ['app', 'scripts', 'server.ts', 'hmr.ts']

/**
 * A named export at the start of a line: `export function name`, `export const name`,
 * `export interface Name` and the other declaration kinds, with an optional `async`. Group 1
 * is the name.
 */
const EXPORT = new RegExp(
  String.raw`^export\s+(?:async\s+)?(?:function\*?|const|let|class|interface|type|enum)\s+` +
    String.raw`([A-Za-z_$][\w$]*)`,
)

/**
 * An `export default` line; the index lists it under the name "default".
 */
const DEFAULT = /^export\s+default\b/

/**
 * Collects every .ts and .tsx file under the roots, skipping the generated bundle.
 *
 * Called by: main (this file)
 * @param root a file or a folder, relative to the working directory
 * @returns the file paths, with forward slashes
 */
function files(root: string): string[] {
  // A file is returned as is.
  if (statSync(root).isFile()) return [root]
  // A folder is walked entry by entry; the bundle and its declaration are skipped.
  return readdirSync(root).flatMap((name) => {
    // The entry's path: the folder plus the name, in the system's separator.
    let path = join(root, name)
    // The React Flow bundle (flow-bundle.js, .js.map, .css) is built, not written: skipped.
    if (name.startsWith('flow-bundle')) return []
    // A folder is walked recursively; a .ts or .tsx file is kept; anything else is dropped.
    return statSync(path).isDirectory() ? files(path) : /\.tsx?$/.test(name) ? [path] : []
  })
}

/**
 * Builds the index and writes it as Markdown.
 *
 * Called by: the script's own top level
 */
function main(): void {
  // Every file, with forward slashes so the index reads the same on any system.
  let all = ROOTS.flatMap(files).map((p) => relative('.', p).split(sep).join('/'))
  // The text of every file, split by line and read once; each file is searched many times.
  let text = new Map(all.map((p) => [p, readFileSync(p, 'utf-8').split('\n')]))
  // The Markdown lines, started with the title and the sentence that says how the file is made.
  let out = [
    '# Callers index',
    '',
    'Generated by `npm run callers`. For each export, the files and lines that mention ' +
      'its name.',
    '',
  ]

  // One section per file that exports something, in the order the files were found.
  for (let file of all) {
    // The names this file exports, in order of appearance.
    let names: string[] = []
    // Each line is tested for a named export, then for a default export.
    for (let line of text.get(file)!) {
      // A named export, if the line is one; group 1 holds the name.
      let m = EXPORT.exec(line)
      // A named export adds its name; a default export adds "default".
      if (m) names.push(m[1]!)
      else if (DEFAULT.test(line)) names.push('default')
    }
    // A file that exports nothing gets no section.
    if (names.length === 0) continue
    // The section heading is the file's path, followed by a blank line.
    out.push(`## ${file}`, '')
    // One bullet per export, with every file and line that mentions it.
    for (let name of names) {
      // The pattern: for "default", an import from this file by name; otherwise the whole word.
      let word =
        name === 'default'
          ? new RegExp(`from '[^']*${file.split('/').pop()!.replace('.', '\\.')}'`)
          : new RegExp(`\\b${name}\\b`)
      // The "file:line" references found, in file order.
      let uses: string[] = []
      // Every other file is searched line by line.
      for (let [other, lines] of text) {
        // A file is not its own caller.
        if (other === file) continue
        // Each matching line is recorded as "file:line", with 1-based line numbers.
        lines.forEach((l, i) => {
          // A line that mentions the name counts as a use.
          if (word.test(l)) uses.push(`${other}:${i + 1}`)
        })
      }
      // The bullet: the name in code font, then the references or the words "no other file".
      out.push(`- \`${name}\`: ${uses.length === 0 ? 'no other file' : uses.join(', ')}`)
    }
    // A blank line closes the section.
    out.push('')
  }

  // The index goes to docs/, created on first run.
  mkdirSync('docs', { recursive: true })
  // The lines are joined with LF and written, replacing the previous index.
  writeFileSync('docs/callers.md', out.join('\n'))
  // A one-line summary for whoever ran the script.
  console.log(`docs/callers.md: ${all.length} files scanned`)
}

// The script runs when loaded; nothing imports it.
main()
